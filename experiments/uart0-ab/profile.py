"""MOS-owned stopped A/B profile with frozen frontend/VDP; never flashes hardware."""
import hashlib,importlib.util,shutil,sys
from pathlib import Path
root=Path(__file__).resolve().parents[2];probe=sys.argv[1:]==['--probe'];b=root/('build/uart0-ab/native-probe' if probe else 'build/uart0-ab/native')
auto=sys.argv[1:]==['--auto'];assert not sys.argv[1:] or auto or probe
p=root/('.emulator/uart0-ab-probe' if probe else '.emulator/uart0-ab-auto' if auto else '.emulator/uart0-ab')
for proc in Path('/proc').glob('[0-9]*'):
 try:
  if (proc/'exe').resolve()==(p/'runtime/flexe-agon-emulator.bin').resolve():raise RuntimeError('Close the active A/B profile before refreshing')
 except (FileNotFoundError,PermissionError):pass
spec=importlib.util.spec_from_file_location('canonical',root/'build/uart0-suite/setup_emulator.py');c=importlib.util.module_from_spec(spec);spec.loader.exec_module(c)
c.link_shared_runtime(p,root.parent/'golem/.emulator/runtime/fab-1.2.5')
r=p/'runtime';r.mkdir(exist_ok=True);base=root/'build/uart0-mos/runtime'
files={'flexe-agon-emulator.bin':base/'flexe-agon-emulator','flexe-vdp.so':base/'flexe-vdp.so','esp32-firmware.bin':base/'esp32-firmware.bin','esp32-firmware.elf':base/'esp32-firmware.elf','mos_platform.bin':root/'build/uart0-mos/MOS.bin','mos_platform.map':root/'build/uart0-mos/MOS.map'}
for n,s in files.items():shutil.copy2(s,r/n);c.replace_symlink(p/n,r/n)
(p/'firmware').unlink();app=p/'sdcard/uart0';app.mkdir(exist_ok=True)
shutil.copyfile(b/'test.bin',app/'test.bin')
shutil.copyfile(root/'experiments/uart0-ab/readme.txt',app/'readme.txt')
(p/'sdcard/autoexec.txt').write_bytes(b'cd /uart0\r\nload test.bin\r\nrun\r\nECHO UART0 AB MOS RETURN\r\n')
(p/'.bespoke-vdp-profile').write_text('flexe-vdp.so\n');c.write_profile_launcher(p,strict_bespoke=True)
launcher=p/'fab-agon-emulator';s=launcher.read_text().replace('fab-agon-emulator.bin','flexe-agon-emulator.bin')
s=s.replace('\nvdp_name=', '''
export AGON_FLEXE_FIRMWARE="$profile_dir/esp32-firmware.bin"
export AGON_FLEXE_ELF="$profile_dir/esp32-firmware.elf"
export AGON_FLEXE_ENGINE="${AGON_FLEXE_ENGINE:-jit}"
export AGON_FLEXE_ARTIFACTS="$profile_dir/last-run"
export MOS_UART_STATS="$profile_dir/last-run/uart.json"
mkdir -p "$AGON_FLEXE_ARTIFACTS"
vdp_name=''',1)
(p/'flexe-agon-emulator').write_text(s);(p/'flexe-agon-emulator').chmod(0o755)
launcher.write_text('#!/usr/bin/env bash\n# Generated by agon-dev-env setup_emulator.py. Project compatibility entry.\nset -euo pipefail\ncd "$(dirname "$0")"\nexec ./flexe-agon-emulator "$@"\n');(p/'fab-agon-emulator.bin').unlink()
(p/'.mos-release').write_text('UART0 development MOS; isolated A/B native ZDS II\n')
(p/'.mos-release.sha256').write_text(''.join(f'{hashlib.sha256((p/n).read_bytes()).hexdigest()}  {n}\n' for n in ('mos_platform.bin','mos_platform.map')))
pins=[*files,'fab-agon-emulator','flexe-agon-emulator','sdcard/uart0/test.bin','sdcard/autoexec.txt','sdcard/uart0/readme.txt']
(p/'.runtime.sha256').write_text(''.join(f'{hashlib.sha256((p/n).read_bytes()).hexdigest()}  {n}\n' for n in pins))
print('Prepared stopped profile',p)
