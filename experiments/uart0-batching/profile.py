"""Create a separate stopped profile; no shared runtime, SD or owner changes."""
import hashlib,importlib.util,shutil
from pathlib import Path
root=Path(__file__).resolve().parents[2];build=root/'build/uart0-batching';native=build/'native'
profile=root/'.emulator/uart0-batching'
for p in Path('/proc').glob('[0-9]*'):
    try:
        if profile.exists() and (p/'exe').resolve()==(profile/'runtime/flexe-agon-emulator.bin').resolve():raise RuntimeError('Batching profile is active')
    except (FileNotFoundError,PermissionError):pass
spec=importlib.util.spec_from_file_location('canonical',root/'build/uart0-suite/setup_emulator.py')
canonical=importlib.util.module_from_spec(spec);spec.loader.exec_module(canonical)
canonical.link_shared_runtime(profile,root.parent/'golem/.emulator/runtime/fab-1.2.5')
runtime=profile/'runtime';runtime.mkdir(exist_ok=True)
product=root/'build/uart0-mos/runtime';esp=root/'build/uart0-margin/firmware/.pio/build/esp32dev'
files={'flexe-agon-emulator.bin':product/'flexe-agon-emulator','flexe-vdp.so':product/'flexe-vdp.so',
'esp32-firmware.bin':esp/'firmware.bin','esp32-firmware.elf':esp/'firmware.elf',
'mos_platform.bin':root/'build/uart0-mos/MOS.bin','mos_platform.map':root/'build/uart0-mos/MOS.map'}
# Runtime hashes are pinned in the earlier qualified MOS and diagnostic receipts.
known={}
for line in (root/'experiments/uart0-mos/runtime.sha256').read_text().splitlines():
    digest,name=line.split(None,1);known[name]=digest
import json
info=json.loads((root/'experiments/uart0-margin/results.json').read_text())
assert hashlib.sha256(files['esp32-firmware.bin'].read_bytes()).hexdigest()==info['firmware']['sha256']
for name in ('flexe-agon-emulator.bin','flexe-vdp.so'):
    key='flexe-agon-emulator' if name.endswith('.bin') else name
    assert hashlib.sha256(files[name].read_bytes()).hexdigest()==known[key]
for name,source in files.items():shutil.copy2(source,runtime/name);canonical.replace_symlink(profile/name,runtime/name)
firmware=profile/'firmware';assert firmware.is_symlink();firmware.unlink()
app=profile/'sdcard/uart0';app.mkdir(exist_ok=True)
# A profile refresh must not turn the next manual run into a create-new file
# collision. Preserve the previous private reports off-profile before clearing.
reports=list(app.glob('*.dat'))
if reports:
    history=build/'preparation-history';history.mkdir(exist_ok=True)
    index=1
    while (history/f'{index:03d}').exists():index+=1
    saved=history/f'{index:03d}';saved.mkdir()
    for report in reports:
        shutil.copyfile(report,saved/report.name);report.unlink()
shutil.copyfile(native/'test.bin',app/'test.bin')
shutil.copyfile(native/'checks.bin',app/'checks.bin')
for n in (1,2,4,8,16):shutil.copyfile(native/f'stress{n}/test.bin',app/f'stress{n}.bin')
commands=b'cd /uart0\r\nload test.bin &80000\r\nrun &80000\r\n'
for n in (1,2,4,8,16):commands+=f'load stress{n}.bin &80000\r\nrun &80000\r\n'.encode()
commands+=b'ECHO UART0 BATCH CAMPAIGN RETURN\r\n'
(profile/'sdcard/autoexec.txt').write_bytes(commands)
(profile/'.bespoke-vdp-profile').write_text('flexe-vdp.so\n')
canonical.write_profile_launcher(profile,strict_bespoke=True)
launcher=profile/'fab-agon-emulator';s=launcher.read_text().replace('fab-agon-emulator.bin','flexe-agon-emulator.bin')
s=s.replace('\nvdp_name=', '''
export AGON_FLEXE_FIRMWARE="$profile_dir/esp32-firmware.bin"
export AGON_FLEXE_ELF="$profile_dir/esp32-firmware.elf"
export AGON_FLEXE_ENGINE="${AGON_FLEXE_ENGINE:-jit}"
export AGON_FLEXE_ARTIFACTS="$profile_dir/last-run"
export MOS_UART_STATS="$profile_dir/last-run/uart.json"
mkdir -p "$AGON_FLEXE_ARTIFACTS"
vdp_name=''',1)
primary=profile/'flexe-agon-emulator';primary.write_text(s);primary.chmod(0o755)
launcher.write_text('#!/usr/bin/env bash\n# Generated by agon-dev-env setup_emulator.py. Project compatibility entry.\nset -euo pipefail\ncd "$(dirname "$0")"\nexec ./flexe-agon-emulator "$@"\n')
(profile/'fab-agon-emulator.bin').unlink()
(profile/'.mos-release').write_text('Experimental UART0 ABI1.2 MOS; native ZDS II; unapproved\n')
(profile/'.mos-release.sha256').write_text(''.join(f'{hashlib.sha256((profile/n).read_bytes()).hexdigest()}  {n}\n' for n in ('mos_platform.bin','mos_platform.map')))
pins=[*files,'fab-agon-emulator','flexe-agon-emulator','sdcard/autoexec.txt',*[str(p.relative_to(profile)) for p in app.glob('*.bin')]]
(profile/'.runtime.sha256').write_text(''.join(f'{hashlib.sha256((profile/n).read_bytes()).hexdigest()}  {n}\n' for n in pins))
print('Prepared stopped profile',profile)
